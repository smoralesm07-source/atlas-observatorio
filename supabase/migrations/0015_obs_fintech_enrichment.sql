create or replace function public.aml_fintech_sync_payment_regulatory()
returns jsonb language plpgsql security definer set search_path='public','pg_temp' as $$
declare rec record; service_code text; v_rows int:=0;
begin
  update public.aml_fintech_candidate cand set matched_fintech_id=e.fintech_id,candidate_status='MATCHED_EXISTING',match_method='EXACT_LEGAL_NAME_CMF_PAYMENT',match_score=0.99
  from public.aml_fintech_entity e
  where cand.source_code='CMF_PAYMENTS' and cand.matched_fintech_id is null and public.obs_normalize_text(cand.name_raw)=public.obs_normalize_text(e.legal_name);
  for rec in select candidate_id,matched_fintech_id,source_url,evidence from public.aml_fintech_candidate where source_code='CMF_PAYMENTS' and matched_fintech_id is not null loop
    for service_code in select jsonb_array_elements_text(coalesce(rec.evidence->'registries','[]'::jsonb)) loop
      insert into public.aml_fintech_regulatory_status(fintech_id,regulator,registry,service,status,source_url,observed_at)
      values(rec.matched_fintech_id,'CMF','CMF_PAYMENTS',service_code,'VIGENTE',rec.source_url,now())
      on conflict(fintech_id,regulator,registry,service) do update set status='VIGENTE',source_url=excluded.source_url,observed_at=now();
      v_rows:=v_rows+1;
    end loop;
  end loop;
  return jsonb_build_object('regulatory_rows_upserted',v_rows);
end; $$;
revoke all on function public.aml_fintech_sync_payment_regulatory() from public,anon,authenticated;
grant execute on function public.aml_fintech_sync_payment_regulatory() to service_role;

create or replace function public.obs_fintech_enrichment_status()
returns jsonb language plpgsql stable security definer set search_path='public','pg_temp' as $$
declare ok boolean; result jsonb;
begin
  select exists(select 1 from public.aml_allowed_users au where au.user_id=auth.uid() and au.enabled) into ok;
  if not ok then return jsonb_build_object('error','NOT_AUTHORIZED'); end if;
  select jsonb_build_object(
    'facts',(select count(*) from public.aml_fintech_enrichment_fact),
    'entity_profiles',(select count(*) from public.aml_fintech_entity where profile_refreshed_at is not null),
    'candidate_profiles',(select count(*) from public.aml_fintech_candidate where enrichment_refreshed_at is not null),
    'identity_hints',(select count(*) from public.aml_fintech_candidate where matched_fintech_id is null and identity_candidate_rut is not null),
    'business_model_classified',(select count(*) from public.aml_fintech_entity where business_model is not null),
    'target_customer_classified',(select count(*) from public.aml_fintech_entity where target_customer is not null),
    'revenue_model_classified',(select count(*) from public.aml_fintech_entity where revenue_model is not null),
    'virtual_asset_signal_subjects',(select count(distinct subject_type||':'||subject_key) from public.aml_fintech_enrichment_fact where field_code='VIRTUAL_ASSET_SIGNAL'),
    'latest_run',(select to_jsonb(x) from (select run_id,run_type,status,rows_requested,rows_processed,rows_failed,payment_rows_seen,started_at,completed_at from public.aml_fintech_enrichment_run order by started_at desc limit 1) x),
    'refreshed_at',(select max(last_seen_at) from public.aml_fintech_enrichment_fact)
  ) into result;
  return result;
end; $$;
revoke all on function public.obs_fintech_enrichment_status() from public,anon;
grant execute on function public.obs_fintech_enrichment_status() to authenticated;

create or replace function public.obs_fintech_enrichment_detail(p_subject_type text,p_subject_key text)
returns jsonb language plpgsql stable security definer set search_path='public','pg_temp' as $$
declare ok boolean; result jsonb;
begin
  select exists(select 1 from public.aml_allowed_users au where au.user_id=auth.uid() and au.enabled) into ok;
  if not ok then return jsonb_build_object('error','NOT_AUTHORIZED'); end if;
  select jsonb_build_object('facts',coalesce(jsonb_agg(jsonb_build_object(
    'field_code',field_code,'value_text',value_text,'value_json',value_json,'evidence_class',evidence_class,'confidence',confidence,
    'source_code',source_code,'source_url',source_url,'evidence_excerpt',evidence_excerpt,'observed_at',observed_at,'last_seen_at',last_seen_at
  ) order by field_code,confidence desc nulls last,last_seen_at desc),'[]'::jsonb)) into result
  from public.aml_fintech_enrichment_fact where subject_type=upper(p_subject_type) and subject_key=p_subject_key;
  return result;
end; $$;
revoke all on function public.obs_fintech_enrichment_detail(text,text) from public,anon;
grant execute on function public.obs_fintech_enrichment_detail(text,text) to authenticated;

create or replace function public.aml_fintech_trigger_enrichment()
returns bigint language plpgsql security definer set search_path='public','vault','net','pg_temp' as $$
declare v_token text; v_request bigint;
begin
  select decrypted_secret into v_token from vault.decrypted_secrets where name='atlas_fintech_cron_token' limit 1;
  if v_token is null then raise exception 'FINTECH_CRON_TOKEN_MISSING'; end if;
  select net.http_post(
    url:='https://ldmtlwzqaqmegedktlxr.supabase.co/functions/v1/atlas-fintech-enrichment',
    body:=jsonb_build_object('limit',8),
    headers:=jsonb_build_object('content-type','application/json','x-atlas-cron-token',v_token),
    timeout_milliseconds:=90000
  ) into v_request;
  return v_request;
end; $$;
revoke all on function public.aml_fintech_trigger_enrichment() from public,anon,authenticated;
grant execute on function public.aml_fintech_trigger_enrichment() to service_role;

