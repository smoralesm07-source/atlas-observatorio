  add column if not exists business_model_confidence numeric(5,4),
  add column if not exists target_customer_basis text,
  add column if not exists target_customer_confidence numeric(5,4),
  add column if not exists revenue_model_basis text,
  add column if not exists revenue_model_confidence numeric(5,4),
  add column if not exists profile_refreshed_at timestamptz;

alter table public.aml_fintech_candidate
  add column if not exists enrichment_status text not null default 'PENDING',
  add column if not exists enrichment_refreshed_at timestamptz,
  add column if not exists identity_candidate_rut text,
  add column if not exists identity_candidate_legal_name text,
  add column if not exists identity_candidate_confidence numeric(5,4),
  add column if not exists identity_candidate_source_url text,
  add column if not exists classification_hint jsonb not null default '{}'::jsonb;

create table if not exists public.aml_fintech_enrichment_fact (
  fact_id bigint generated by default as identity primary key,
  evidence_key text not null unique,
  subject_type text not null check (subject_type in ('ENTITY','CANDIDATE')),
  subject_key text not null,
  field_code text not null,
  value_text text,
  value_json jsonb not null default '{}'::jsonb,
  evidence_class text not null check (evidence_class in ('OBSERVED_OFFICIAL','DECLARED','INFERRED')),
  confidence numeric(5,4) check (confidence between 0 and 1),
  source_code text references public.aml_fintech_source_catalog(source_code),
  source_url text,
  evidence_excerpt text,
  first_seen_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now(),
  observed_at timestamptz not null default now()
);

create table if not exists public.aml_fintech_enrichment_run (
  run_id bigint generated by default as identity primary key,
  run_type text not null default 'WEB_PROFILE',
  status text not null default 'STARTED',
  rows_requested integer not null default 0,
  rows_processed integer not null default 0,
  rows_failed integer not null default 0,
  payment_rows_seen integer not null default 0,
  detail jsonb not null default '{}'::jsonb,
  started_at timestamptz not null default now(),
  completed_at timestamptz
);

create index if not exists aml_fintech_enrichment_subject_idx on public.aml_fintech_enrichment_fact(subject_type,subject_key,last_seen_at desc);
create index if not exists aml_fintech_enrichment_field_idx on public.aml_fintech_enrichment_fact(field_code,subject_type);
create index if not exists aml_fintech_enrichment_source_idx on public.aml_fintech_enrichment_fact(source_code,last_seen_at desc);

alter table public.aml_fintech_enrichment_fact enable row level security;
